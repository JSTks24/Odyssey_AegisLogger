const strings: Record<Locale, Record<string, string>> = {
    en,
    "zh-CN": zhCN
};

export function getLocale(): Locale {
    let preference = "auto";
    try {
        preference = settings.store.language ?? "auto";
    } catch { }
    if (preference === "zh-CN" || preference === "en") return preference;
    return navigator.language?.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function t(key: string, params?: Record<string, string | number>): string {
    const locale = getLocale();
    let text = strings?.[locale]?.[key] ?? strings?.en?.[key] ?? key;
    if (params) {
        for (const [name, value] of Object.entries(params))
            text = text.replaceAll(`{${name}}`, String(value));
    }
    return text;
}

export function tabDisplayName(tab: "Deleted" | "Edited" | "Ghost Pinged"): string {
    switch (tab) {
        case "Deleted": return t("modal.tab.deleted");
        case "Edited": return t("modal.tab.edited");
        default: return t("modal.tab.ghostPinged");
    }
}
